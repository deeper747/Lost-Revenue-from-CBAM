// Build the UK CBAM data modules the calculator imports.
//
//   data/uk/uk_cbam_default_values.csv                  -> src/data/ukCbamDefaultValues.js
//   data/uk/raw/uktradeinfo_us_cbam_imports_monthly.csv -> src/data/ukTradeData.js
//
// The default-values CSV is parsed from HMRC's "Check the default values for the CBAM"
// guidance (published 16 Oct 2026), and the trade CSV comes from scripts/fetch_uk_trade.py.
// Re-run this after either input changes:  node scripts/build_uk_data.mjs
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

function parseCsv(text) {
  const rows = [];
  let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); cell = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else cell += c;
  }
  if (cell !== "" || row.length) { row.push(cell); rows.push(row); }
  const [head, ...body] = rows;
  return body.map(r => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const dv = parseCsv(readFileSync(join(ROOT, "data/uk/uk_cbam_default_values.csv"), "utf8"));
const trade = parseCsv(readFileSync(join(ROOT, "data/uk/raw/uktradeinfo_us_cbam_imports_monthly.csv"), "utf8"));

const dvRows = dv.map(r => [r.cn_code, r.description, r.sector, Number(r.default_value_tco2e_per_t)]);
writeFileSync(join(ROOT, "src/data/ukCbamDefaultValues.js"),
`// GENERATED by scripts/build_uk_data.mjs — do not edit by hand.
//
// UK CBAM default values, one per CN8 code, in tCO2e per tonne of product. Source: HMRC,
// "Check the default values for the Carbon Border Adjustment Mechanism (CBAM)", published
// 16 October 2026, replicating The CBAM (Default Values) Force of Law Notice (Draft).
// The values apply regardless of origin, are in force 1 Jan 2027 to 31 Dec 2028, and
// ALREADY INCLUDE a 10% mark-up in every sector except fertiliser (no mark-up).
// Do not apply a mark-up on top of them.
// Columns: [CN8 code, CN description, sector, default value incl. mark-up]
export const UK_DEFAULT_VALUE_ROWS = ${JSON.stringify(dvRows)};

export const UK_DV_PUBLISHED = "2026-10-16";
`);

const tr = {};
let maxYm = "";
for (const r of trade) {
  const t = Number(r.tonnes), v = Number(r.gbp);
  if (!(t > 0) && !(v > 0)) continue;
  (tr[r.cn_code] ||= {})[r.month] = [Math.round(t * 1000) / 1000, Math.round(v)];
  if (r.month > maxYm) maxYm = r.month;
}
writeFileSync(join(ROOT, "src/data/ukTradeData.js"),
`// GENERATED by scripts/build_uk_data.mjs — do not edit by hand.
//
// UK imports from the United States of UK CBAM goods, by CN8 and month.
// Source: HMRC Overseas Trade Statistics via the uktradeinfo API (FlowTypeId 3, non-EU
// imports; CountryId 400, United States), summed across ports. Values: [tonnes, GBP].
// A CN code with no entry for a month had no recorded US imports that month.
export const UK_TRADE = ${JSON.stringify(tr)};

export const UK_TRADE_LATEST_YM = "${maxYm}";
`);
console.log(`default values: ${dvRows.length} codes; trade: ${Object.keys(tr).length} codes through ${maxYm}`);
